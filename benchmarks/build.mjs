// `<template id="Counter:row">` -> `<template id="<Prefix>Counter:row">`.
// A bare `<template>` names the file's single unnamed component, so it becomes
// `id="<Prefix>"` — the `Prefix:main` view. `macro:` ids would need their call
// sites rewritten too; no view file declares one, so it is an error here.
function prefixTemplates(source, prefix, path) {
  return source.replace(/<template([^>]*)>/g, (whole, attrs) => {
    const m = attrs.match(/\bid\s*=\s*"([^"]*)"/);
    if (!m) {
      if (/\bid\s*=/.test(attrs)) {
        throw new Error(`${path}: unquoted template id, not supported`);
      }
      return `<template id="${prefix}"${attrs}>`;
    }
    const id = m[1];
    if (id.startsWith("macro:")) {
      throw new Error(`${path}: macro templates would need call-site rewriting`);
    }
    const colon = id.indexOf(":");
    const renamed =
      colon < 0 ? prefix + id : prefix + id.slice(0, colon) + id.slice(colon);
    return whole.replace(m[0], `id="${renamed}"`);
  });
}

const parts = [
  "<!-- GENERATED by benchmarks/build.mjs — do not edit. -->",
  "<!-- Every view .html in the repo, component names prefixed per file. -->",
];
for (const [path, prefix] of VIEWS) {
  const source = readFileSync(join(root, path), "utf8");
  parts.push(`<!-- ${path} (${prefix}) -->`);
  parts.push(prefixTemplates(source, prefix, path).trimEnd());
}
const html = parts.join("\n") + "\n";
writeFileSync(join(root, "benchmarks/all_views.html"), html);

// The MoonBit twin. `#|` is a raw multi-line string: no interpolation, so the
// `{...}` and `\` a view body is full of need no escaping.
const lines = html.replace(/\n$/, "").split("\n");
const mbt = `// GENERATED by benchmarks/build.mjs from benchmarks/all_views.html —
// do not edit; regenerate with \`cmd/dev -- bench-views\`.

///|
/// Every view .html in the repo concatenated into one view file, component
/// names prefixed per source file so nothing collides. ${lines.length} lines,
/// ${lines.join("\n").length} chars (the .html's trailing newline aside), the
/// workload benchmarks/cmd/viewparse parses.
pub let all_views : String =
${lines.map(l => `  #|${l}`).join("\n")}
`;
writeFileSync(join(root, "benchmarks/all_views_gen.mbt"), mbt);

const templates = (html.match(/<template/g) ?? []).length;
console.log(
  `benchmarks/all_views.html: ${VIEWS.length} files, ${templates} views, ` +
    `${lines.length} lines, ${html.length} chars`,
);
