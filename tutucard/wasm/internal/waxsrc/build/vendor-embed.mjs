// Embed vendor/wax/*.wax into gen/stdlib_src_gen.mbt.
//
// The Wax standard library is distributed as `.wax` SOURCE — Wax has no import
// system, so a consumer concatenates the files in a fixed order and compiles
// the whole thing as one module. The generator needs that text at run time, in
// a browser, where there is no filesystem; so it is compiled in, the same way
// `cli/skill_assets_gen.mbt` compiles in the skill tree for a binary that has
// no package directory to copy from.
//
// The vendored files are the single source. Re-vendor from upstream (see
// vendor/wax/README.md), rerun this, and commit both halves; the drift check is
// rerun-and-`git diff --exit-code`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const MODULE = join(HERE, "..");
const VENDOR = join(MODULE, "vendor", "wax");
const OUT = join(MODULE, "stdlib_src_gen.mbt");

// Fixed, and load-bearing: Wax resolves in one pass over one module, so a file
// must follow everything it names. From the upstream stdlib/README.md.
const ORDER = [
  "hashing.wax",
  "persistent_hash_map.wax",
  "persistent_hash_set.wax",
  "persistent_vector.wax",
  "utf8.wax",
  "immutable_value.wax",
  "record.wax",
];

// A MoonBit double-quoted string literal. Escaping `\` first also neutralizes
// `\{`, which is MoonBit's string interpolation and would otherwise turn a Wax
// escape into a compile error.
function mbtString(s) {
  let out = '"';
  for (const c of s) {
    if (c === "\\") out += "\\\\";
    else if (c === '"') out += '\\"';
    else if (c === "\n") out += "\\n";
    else if (c === "\r") out += "\\r";
    else if (c === "\t") out += "\\t";
    else out += c;
  }
  return out + '"';
}

// cardwasm's own fixed runtime, which is Wax source for the same reason the
// stdlib is: it is the same in every card, so there is nothing for a generator
// to decide. `runtime/` is HAND-WRITTEN and lives here, unlike `vendor/`.
const RUNTIME = join(MODULE, "runtime");
const RUNTIME_ORDER = ["runtime.wax"];
// Concatenated one at a time, never together: which one a card gets decides
// its import section. See runtime/lower_scalar.wax.
const LOWER_ORDER = ["lower_scalar.wax", "lower_values.wax"];
// Carried only by a card that uses what is in them. Zero, one or several, in
// this order, after the lowering half. See runtime/parse_num.wax.
const OPTIONAL_ORDER = ["parse_num.wax", "send_at.wax", "contract_log.wax", "escape_help.wax"];

const parts = ORDER.map((name) => [name, readFileSync(join(VENDOR, name), "utf8")]);
const runtimeParts = RUNTIME_ORDER.map((n) => [n, readFileSync(join(RUNTIME, n), "utf8")]);
const lowerParts = LOWER_ORDER.map((n) => [n, readFileSync(join(RUNTIME, n), "utf8")]);
const optionalParts = OPTIONAL_ORDER.map((n) => [n, readFileSync(join(RUNTIME, n), "utf8")]);

const body = parts
  .map(([name, src]) => `  (${mbtString(name)}, ${mbtString(src)}),`)
  .join("\n");
const runtimeBody = runtimeParts
  .map(([name, src]) => `  (${mbtString(name)}, ${mbtString(src)}),`)
  .join("\n");
const lowerBody = lowerParts
  .map(([name, src]) => `  (${mbtString(name)}, ${mbtString(src)}),`)
  .join("\n");
const optionalBody = optionalParts
  .map(([name, src]) => `  (${mbtString(name)}, ${mbtString(src)}),`)
  .join("\n");

const source = `// GENERATED by \`node build/vendor-embed.mjs\` from tutucard/wasm/vendor/wax/.
// DO NOT EDIT. Re-vendor upstream, rerun the script, commit both halves.

///|
/// The Wax standard library, in concatenation order, as (filename, source).
///
/// The names are here for diagnostics: a \`BadModule\` that points into the
/// stdlib is a cardwasm bug, and knowing which file it landed in is most of
/// finding it. Nothing else reads them.
pub let stdlib_files : Array[(String, String)] = [
${body}
]

///|
/// The same thing concatenated, which is the form the parser wants.
///
/// Wax has no import system: the stdlib IS its concatenation, compiled as one
/// module ahead of whatever uses it. The order is fixed upstream and mirrored
/// in \`build/vendor-embed.mjs\`.
pub let stdlib_src : String = {
  let sb = StringBuilder::new()
  for f in stdlib_files {
    sb.write_string(f.1)
    sb.write_string("\\n")
  }
  sb.to_string()
}

///|
/// cardwasm's own fixed runtime, from \`runtime/\`. Hand-written, not vendored.
pub let runtime_files : Array[(String, String)] = [
${runtimeBody}
]

///|
pub let runtime_src : String = {
  let sb = StringBuilder::new()
  for f in runtime_files {
    sb.write_string(f.1)
    sb.write_string("\\n")
  }
  sb.to_string()
}

///|
/// The two lowering halves, by name. Exactly ONE is ever concatenated: which
/// decides whether the module imports the \`values\` arena, and a host reads the
/// import section to know what a guest can do.
pub let lower_files : Array[(String, String)] = [
${lowerBody}
]

///|
/// The lowering half named, or the empty string if there is no such half.
pub fn lower_src(name : String) -> String {
  for f in lower_files {
    if f.0 == name {
      return f.1
    }
  }
  ""
}

///|
/// The pieces of the runtime a card carries only if it uses them.
///
/// Wax's emitter does no dead-code elimination, so every function in the fixed
/// runtime is in every module whether or not anything calls it. That is the
/// right trade for the parts every card needs and the wrong one for the parts
/// two cards in ten do — so those live here, and the generator says which it
/// wants. The lowering halves next door make the same split about the IMPORT
/// section; this one is about size.
pub let optional_files : Array[(String, String)] = [
${optionalBody}
]

///|
/// The optional piece named, or the empty string if there is no such piece.
pub fn optional_src(name : String) -> String {
  for f in optional_files {
    if f.0 == name {
      return f.1
    }
  }
  ""
}
`;

writeFileSync(OUT, source);
const bytes = parts.reduce((n, [, s]) => n + s.length, 0);
console.log(`embedded ${parts.length} files (${(bytes / 1024).toFixed(0)} KB of Wax) into ${OUT}`);
