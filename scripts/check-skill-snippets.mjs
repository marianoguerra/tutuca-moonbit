// Compile-check the MoonBit snippets in the bundled skill (skill/tutuca/**.md).
//
// The skill ships INSIDE the CLI binary (cli/skill_assets_gen.mbt) and is the
// only thing an agent reads before writing tutuca code, so a snippet naming a
// parameter the library dropped is worse than no snippet. Nothing compiled these
// until this check existed, and they rotted: `specs=` / `FieldSpec::comp(...)`
// survived in five files across two releases after the parameter was removed.
//
// A snippet is checked against the REAL generated surface, not a stub. Most
// recipes show both halves — an ```html view file, then the ```moonbit that uses
// it — so this pairs them, runs the same view generator the playground runs
// (viewgen/ compiled to JS), and compiles the pair together. That is what makes
// the check able to catch a wrong wrapper parameter at all.
//
// Fence tags are load-bearing:
//   ```moonbit            checked; must declare top-level items (fn/struct/test/let)
//   ```moonbit fragment   a body fragment; wrapped in a fn before compiling
//   ```moonbit nocheck    skipped; REQUIRES a `// nocheck: <reason>` line
//
// An ```html view file is generated whether or not a ```moonbit block follows
// it: a recipe whose whole answer is the view file — a schema and a
// `tutuca/script` block, with nothing left for MoonBit to do — is the shape
// these docs aim for, and it would otherwise be the one shape nothing checks.
// A generation that succeeds but reports a `script-refusal` FAILS here: the
// module compiles, but an arm the snippet shows in the block would silently
// fall through to MoonBit, which is the opposite of what the recipe teaches.
//
// Run:
//   moon build --target js playground/viewgen_js   # the generator
//   node scripts/check-skill-snippets.mjs
import { readdirSync, mkdirSync, rmSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const SKILL = join(REPO, "skill/tutuca");
const SCAFFOLD = join(REPO, "skill/_snippets_check");
const VIEWGEN = join(REPO, "_build/js/debug/build/playground/viewgen_js/viewgen_js.js");

// The packages a skill snippet may reach for. Wider than the playground check's
// mirror: skill snippets show harness tests (@harness), call NullCtx (which the
// module-root facade does not re-export, so `core` under the @tutuca alias), and
// document the CSS compile step (@css).
const MOON_PKG = `// generated by scripts/check-skill-snippets.mjs — never committed
import {
  "marianoguerra/tutuca/core" @tutuca,
  "marianoguerra/tutuca/component",
  "marianoguerra/tutuca/anode",
  "marianoguerra/tutuca/app",
  "marianoguerra/tutuca/render",
  "marianoguerra/tutuca/vdom",
  "marianoguerra/tutuca/transactor",
  "marianoguerra/tutuca/css",
  "marianoguerra/tutuca/testing/harness",
  "moonbitlang/core/debug",
  "moonbitlang/core/json",
}

// a snippet imports a subset each, so unused-package (0029) and unused-value
// (44) noise is expected and says nothing about the snippet
warnings = "-44-29"
`;

if (!existsSync(VIEWGEN)) {
  console.error(
    `view generator missing: ${VIEWGEN}\n  build it with: moon build --target js playground/viewgen_js`,
  );
  process.exit(1);
}
new Function(readFileSync(VIEWGEN, "utf8"))();

function markdownFiles(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (e.isDirectory()) out.push(...markdownFiles(join(dir, e.name)));
    else if (e.name.endsWith(".md")) out.push(join(dir, e.name));
  }
  return out;
}

// Fenced blocks in source order, each tagged with the heading it sits under, so
// a moonbit block can find the html block above it and snippets from unrelated
// sections never land in the same package. Nested fences do not occur in these
// files; a plain scan is enough.
function blocksOf(text) {
  const out = [];
  const lines = text.split("\n");
  let open = null;
  let heading = "(top)";
  lines.forEach((line, i) => {
    if (open === null) {
      const h = /^#{1,6}\s+(.*)$/.exec(line);
      if (h) { heading = h[1].trim(); return; }
    }
    const m = /^```(\S*)(.*)$/.exec(line);
    if (!m) return;
    if (open === null) {
      open = { lang: m[1], attrs: m[2].trim(), start: i, heading };
    } else if (m[1] === "") {
      out.push({ ...open, end: i });
      open = null;
    }
  });
  if (open) throw new Error("unterminated fence");
  return out.map((b) => ({ ...b, body: lines.slice(b.start + 1, b.end).join("\n") }));
}

// ---------------------------------------------------------------------------
// The identifier check.
//
// Many snippets are BUCKET-ARGUMENT fragments (`update=(s, msg, ctx) => ...,`),
// which is the right shape for the doc and not a compilable item — so the
// compiler never sees them. That is also exactly where the rot lived: `specs=`
// and `FieldSpec::comp(...)` were bucket arguments. So every block, `nocheck`
// ones included, is additionally checked against the checked-in interface files:
// a `@pkg.Name` must exist in that package's .mbti, and a `name=` keyword
// argument to component()/a generated wrapper must be a real parameter.
//
// This is a spell-checker, not a type-checker. It only reports a name that
// appears NOWHERE, which is the drift a rename or a removal produces.
const MBTI = new Map(); // alias -> text of the package's .mbti
for (const [alias, pkg] of [
  ["tutuca", "core"], ["component", "component"], ["anode", "anode"],
  ["app", "app"], ["render", "render"], ["vdom", "vdom"],
  ["transactor", "transactor"], ["css", "css"], ["harness", "testing/harness"],
  ["statedef", "statedef"], ["lint", "lint"], ["viewgen", "viewgen"],
  ["memdom", "testing/memdom"], ["inspector", "storybook/inspector"],
  ["sb", "storybook"], ["sbui", "storybook/ui"], ["sbw", "storybook/ui/wasm"],
]) {
  const f = join(REPO, pkg, "pkg.generated.mbti");
  if (existsSync(f)) MBTI.set(alias, readFileSync(f, "utf8"));
}
// Every keyword parameter name of every public function in every package, read
// off the .mbti files rather than hardcoded. A `name=` argument in a snippet has
// to be one of these SOMEWHERE — which is a loose test, and deliberately: it
// reports only a name no API takes at all, the state a removed or renamed
// parameter leaves behind. `specs=` lands here; `slot_args=` does not.
// Keyword arguments of the moonbitlang builtins snippets legitimately use, which
// are in no tutuca .mbti: `inspect(x, content=...)` above all.
const ALL_PARAMS = new Set(["content", "loc", "args_loc", "msg"]);
for (const t of MBTI.values()) {
  for (const [, name] of t.matchAll(/(\w+)\??\s*[:~]/g)) ALL_PARAMS.add(name);
}

function identifierProblems(body) {
  const bad = [];
  for (const [, alias, name] of body.matchAll(/@(\w+)\.([A-Za-z_]\w*)/g)) {
    const t = MBTI.get(alias);
    if (t === undefined) continue; // an alias this check does not know
    if (!new RegExp(`\\b${name}\\b`).test(t)) {
      bad.push(`@${alias}.${name} is in no .mbti for that package`);
    }
  }
  // A keyword argument at the start of a line: `name=` or `name~`. Excludes
  // `=>` (a match arm), `==` and `>=`/`<=` by requiring the next char is not
  // one of them.
  for (const [, name] of body.matchAll(/^[ \t]{0,4}([a-z]\w*)\s*(?:=(?![=>])|~[,)\s])/gm)) {
    if (!ALL_PARAMS.has(name)) {
      bad.push(`\`${name}=\` is not a keyword parameter of any tutuca API — was it removed or renamed?`);
    }
  }
  return [...new Set(bad)];
}

const units = [];
const skipped = [];
const errors = [];

for (const file of markdownFiles(SKILL)) {
  const rel = relative(REPO, file);
  let blocks;
  try {
    blocks = blocksOf(readFileSync(file, "utf8"));
  } catch (e) {
    errors.push([rel, e.message]);
    continue;
  }
  let lastHtml = null;
  let lastHeading = null;
  let n = 0;
  for (const b of blocks) {
    // a view file only pairs with snippets in its OWN section
    if (b.heading !== lastHeading) { lastHtml = null; lastHeading = b.heading; }
    if (b.lang === "html") {
      // Only a view FILE is a usable pair half — a bare markup fragment has no
      // schema and no <template>, so it would generate nothing.
      lastHtml = /<template|tutuca\/state/.test(b.body) ? b.body : null;
      // Generated even when no ```moonbit block follows it. A recipe whose
      // whole answer is the view file — a schema and a script block, with
      // nothing left for MoonBit to do — is exactly the shape the patterns
      // aim for, and it would otherwise be the one shape nothing checks.
      if (lastHtml !== null) pushHtml(`${rel} § ${b.heading}`, lastHtml);
      continue;
    }
    if (b.lang !== "moonbit") continue;
    n += 1;
    const name = `${rel}#${n} (line ${b.start + 1})`;
    // Every block, whatever its tag: a `nocheck` fragment is not exempt from
    // naming APIs that exist.
    for (const p of identifierProblems(b.body)) errors.push([name, p]);
    if (b.attrs === "nocheck") {
      if (!/^\s*\/\/\s*nocheck:\s*\S/m.test(b.body)) {
        errors.push([name, "bare `nocheck` — add a `// nocheck: <reason>` line saying why it cannot compile"]);
      } else {
        skipped.push(name);
      }
      continue;
    }
    if (b.attrs && b.attrs !== "fragment") {
      errors.push([name, `unknown fence attribute \`${b.attrs}\` — use nothing, \`fragment\`, or \`nocheck\``]);
      continue;
    }
    const mbt = b.attrs === "fragment"
      ? `///|\nfn snippet_${n}() -> Unit {\n${b.body}\n}\n`
      : b.body;
    pushUnit(`${rel} § ${b.heading}`, { name, mbt, html: lastHtml, line: b.start + 1 });
  }
}

// One unit PER FILE, not per block: a file's snippets tell one story and refer to
// each other (a test block calls the `counter_module()` a block above it defines).
// Checking them together is both how they are meant to be read and the only way
// they can compile without inventing stubs the reader never sees.
//
// Each paired view file is generated into its own module, so a file may show
// several. They must name distinct components (`<template id="Counter">`), which
// a view file worth showing does anyway.
// The name an UNNAMED `<template>` belongs to. The real CLI takes it from
// `--name` or the file's basename; a doc snippet has neither, but its schema
// block names the component — and `state FilePicker` is exactly the
// `FilePicker` the prose then calls `file_picker_component`.
function fallbackName(html, i) {
  const m = /\bstate\s+([A-Z]\w*)\s*\{/.exec(html);
  return m ? m[1] : `View${i}`;
}

function unitFor(rel) {
  let u = units.find((x) => x.file === rel);
  if (!u) {
    u = { file: rel, name: rel, blocks: [], htmls: [] };
    units.push(u);
  }
  return u;
}

function pushHtml(rel, html) {
  const u = unitFor(rel);
  if (!u.htmls.includes(html)) u.htmls.push(html);
}

function pushUnit(rel, block) {
  const u = unitFor(rel);
  u.blocks.push(block);
  if (block.html !== null && !u.htmls.includes(block.html)) u.htmls.push(block.html);
}

const failures = [];
try {
  mkdirSync(SCAFFOLD, { recursive: true });
  writeFileSync(join(SCAFFOLD, "moon.pkg"), MOON_PKG);
  for (const u of units) {
    for (const f of readdirSync(SCAFFOLD)) {
      if (f !== "moon.pkg") rmSync(join(SCAFFOLD, f));
    }
    // A comment header per block, so a compiler error's line number can be
    // traced back to the markdown line it came from.
    writeFileSync(
      join(SCAFFOLD, "snippet.mbt"),
      u.blocks.map((b) => `// --- ${b.name}\n${b.mbt}`).join("\n"),
    );

    let genFailed = false;
    u.htmls.forEach((html, i) => {
      if (genFailed) return;
      const r = JSON.parse(globalThis.__tutucaViewgen(html, fallbackName(html, i)));
      if (!r.ok) {
        failures.push([u.name, `view generation failed: ${r.error}\n`]);
        genFailed = true;
        return;
      }
      // A script-refusal is not a generation failure — the module compiles and
      // the name falls through to MoonBit. It IS a documentation failure: the
      // snippet shows a block that silently does nothing in a compiled
      // component, which is the opposite of what these recipes teach. Either
      // write the arm the block can compile, or show it as the MoonBit half.
      // …and `mutator-as-message`, for the same reason one rank up: a snippet
      // teaching `@on.click="removeInItemsAt @key"` teaches a button that does
      // nothing, because a generated mutator does not answer a message. The
      // skill is what an agent reads before writing any tutuca code, so a
      // recipe showing the spelling that fails is worse than no recipe.
      const refused = (r.hints ?? []).filter(
        (h) => h.includes("script-refusal") || h.includes("mutator-as-message"),
      );
      if (refused.length) {
        failures.push([u.name, `${refused.join("\n")}\n`]);
        genFailed = true;
        return;
      }
      writeFileSync(join(SCAFFOLD, `_views_${i}.mbt`), r.module);
      if (r.ir) writeFileSync(join(SCAFFOLD, `_views_${i}_ir.mbt`), r.ir);
    });
    if (genFailed) {
      console.log(`FAILED  ${u.name}`);
      continue;
    }

    const tag = `${u.blocks.length} block${u.blocks.length === 1 ? "" : "s"}` +
      `${u.htmls.length ? `, ${u.htmls.length} view file${u.htmls.length === 1 ? "" : "s"}` : ""}`;
    // Judge on ERRORS, not exit status. A doc snippet is unused by construction,
    // so unused_value / unused_field / struct_never_constructed fire on almost
    // every one and say nothing about whether it is correct.
    let out = "";
    try {
      out = execSync("moon check skill/_snippets_check --target js", {
        cwd: REPO,
        stdio: ["ignore", "pipe", "pipe"],
      }).toString();
    } catch (e) {
      out = `${e.stdout ?? ""}${e.stderr ?? ""}`;
    }
    const errs = out.split(/^(?=Error:|Warning:)/m).filter((c) => c.startsWith("Error:"));
    if (errs.length === 0) {
      console.log(`ok      ${u.name}  (${tag})`);
    } else {
      console.log(`FAILED  ${u.name}  (${tag})`);
      failures.push([u.name, errs.join("")]);
    }
  }
} finally {
  rmSync(SCAFFOLD, { recursive: true, force: true });
}

for (const [name, out] of [...errors, ...failures]) {
  console.error(`\n=== ${name} ===\n${out}`);
}
const blocks = units.reduce((n, u) => n + u.blocks.length, 0);
const total = blocks + skipped.length;
console.log(
  `\n${units.length - failures.length}/${units.length} skill sections compile` +
  ` (${blocks} of ${total} blocks compiled; ${skipped.length} are nocheck fragments,` +
  ` identifier-checked only)`,
);
if (skipped.length) {
  console.log(
    `note: a nocheck block is NOT compile-verified. Every block, nocheck included,` +
    ` is checked against the .mbti files for names that no longer exist.`,
  );
}
process.exit(errors.length + failures.length ? 1 : 0);
