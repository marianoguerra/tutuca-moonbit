// Regenerate `anode/sanitize/spec_default_gen.mbt` from the WHATWG/WICG
// Sanitizer API's own builtin configuration files.
//
// The allow-list has to come from the specification rather than from a summary
// of it, because an entry quietly lost is a component that mysteriously fails
// to render and one quietly gained is a hole. Reading it off MDN or off a blog
// post is exactly the failure this guards against — and the first attempt at
// this DID read a summary, which dropped `<u>` and collapsed `<h1>`–`<h6>` into
// one row.
//
// The source is `builtins/` in the spec repo, which is machine-readable and is
// what the spec's own prose is generated from — so it cannot disagree with the
// text the way a hand transcription can. `SPEC_COMMIT` pins it: a moving `main`
// would mean the committed .mbt and this script silently stop corresponding.
//
// To pick up a spec change: bump SPEC_COMMIT, re-run, and commit the pin
// together with the regenerated file. Read the diff — this is an allow-list,
// and both directions of change matter.
//
// Run:  node scripts/fetch-sanitizer-defaults.mjs
//
// `--check` regenerates into memory and compares, but note what it can and
// cannot tell you: this script emits UNFORMATTED MoonBit, and the committed
// file has been through `moon fmt`, so a byte comparison reports "stale" on a
// file whose content is identical. It answers "did the SPEC change" only if
// the committed file happens not to have been formatted since.
//
// The honest check is the `sanitizer-defaults` task: regenerate, `moon fmt`,
// then `git diff --exit-code` — the same shape `skill-embed` and `gen`
// use, and the one that compares like with like.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

// WICG/sanitizer-api, pinned. 2026-06-12.
export const SPEC_COMMIT = "dd981ec525c49c63e51820fa162b4337a1f1512e";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "anode/sanitize/spec_default_gen.mbt");

const RAW = (path) =>
  `https://raw.githubusercontent.com/WICG/sanitizer-api/${SPEC_COMMIT}/${path}`;

// The three namespaces anode can express, which is also all the spec uses.
const NS = {
  "http://www.w3.org/1999/xhtml": "html",
  "http://www.w3.org/2000/svg": "svg",
  "http://www.w3.org/1998/Math/MathML": "mathml",
};

async function getJson(path) {
  const res = await fetch(RAW(path));
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
}

// A MoonBit string literal. The spec's names are ASCII, but escaping rather
// than trusting that keeps a surprising name from producing a file that does
// not compile.
const lit = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

function elementRule(e) {
  const ctor = NS[e.namespace];
  if (!ctor) throw new Error(`unknown namespace ${e.namespace} for ${e.name}`);
  const head = `${ctor}(${lit(e.name)})`;
  const attrs = (e.attributes ?? []).map((a) => {
    if (a.namespace) {
      throw new Error(`namespaced attribute ${a.name} on ${e.name}: anode ` +
        `attribute names carry no namespace, so this cannot be represented`);
    }
    return a.name;
  });
  if (attrs.length === 0) return `    ElementRule::of(${head}),`;
  const list = attrs.map(lit).join(", ");
  return `    { elem: ${head}, attributes: Some([${list}]), remove_attributes: None },`;
}

export async function generate() {
  const def = await getJson("builtins/safe-default-configuration.json");
  const baseline = await getJson("builtins/safe-baseline-configuration.json");

  for (const key of ["elements", "attributes", "comments", "dataAttributes"]) {
    if (!(key in def)) throw new Error(`default config has no ${key}`);
  }
  if (def.processingInstructions?.length) {
    throw new Error("default config now allows processing instructions, which " +
      "anode has no node type for — the port needs a decision, not a regen");
  }

  const elements = def.elements.map(elementRule).join("\n");
  const attributes = def.attributes.map((a) => {
    if (a.namespace) throw new Error(`namespaced global attribute ${a.name}`);
    return a.name;
  });

  // Wrapped by hand rather than by a formatter: `moon fmt` is not run over this
  // file, so the generator owns the line length.
  const attrLines = [];
  let line = "    ";
  for (const a of attributes.map(lit)) {
    if (line.length + a.length + 2 > 78) {
      attrLines.push(line.trimEnd());
      line = "    ";
    }
    line += a + ", ";
  }
  if (line.trim()) attrLines.push(line.trimEnd());

  const baselineNames = baseline.removeElements
    .map((e) => `${NS[e.namespace]}:${e.name}`)
    .sort();

  const counts = {};
  for (const e of def.elements) counts[NS[e.namespace]] = (counts[NS[e.namespace]] ?? 0) + 1;

  return `// Generated by scripts/fetch-sanitizer-defaults.mjs — DON'T EDIT IT.
//
// Source: WICG/sanitizer-api, builtins/safe-default-configuration.json, at
// commit ${SPEC_COMMIT}.
//
// ${def.elements.length} elements (${counts.html} HTML, ${counts.svg} SVG, ${counts.mathml} MathML), \
${attributes.length} global attributes,
// comments: ${def.comments}, dataAttributes: ${def.dataAttributes}.
//
// The spec's baseline at the same commit removes: ${baselineNames.join(", ")}.
// \`unsafe_elements\` in default.mbt is checked against that list by a test.

///|
/// The Sanitizer API's built-in **default configuration**, transcribed.
///
/// This is NOT \`SanitizerConfig::default()\`, and the difference is the whole
/// reason it needs its own name. Two things share the word "default" in the
/// spec: the BASELINE, which is the unsafe elements and the event handlers and
/// is what tutuca applies unconditionally; and this, an opinionated allow-list
/// that additionally drops anything usable for exfiltration, clickjacking or
/// spoofing, plus comments and \`data-*\`.
///
/// **It allows no interactive or media element at all** — no \`button\`, no
/// \`input\`, no \`img\`, no \`form\`, no \`select\`, no \`label\`. That is correct for
/// what the spec's default is for, which is pasting document content into a
/// page. It is wrong for a tutuca view, which is a description of an
/// INTERACTIVE COMPONENT: adopting it as the default would refuse essentially
/// every real guest, starting with any that has a button.
///
/// So it is offered, not imposed. A host whose guests really are document
/// content — a comment renderer, a CMS body — hands it to
/// \`Policy::with_sanitizer\` and gets the platform's own answer. A host
/// rendering components writes an allow-list of its own, or stays on the
/// baseline.
///
/// Note also that \`comments: false\` here is the spec's choice and not a safe
/// one for tutuca: \`ANode::parse\` synthesizes \`Comment\` nodes for its own error
/// paths, so a config that drops comments turns a guest's typo into a refusal
/// about something else. See \`Sanitizer::default\`.
pub fn SanitizerConfig::spec_default() -> SanitizerConfig {
  {
    ..SanitizerConfig::empty(),
    elements: Some([
${elements}
    ]),
    attributes: Some([
${attrLines.join("\n")}
    ]),
    comments: Some(${def.comments}),
    data_attributes: Some(${def.dataAttributes}),
  }
}

///|
/// The elements the spec's baseline removes, at the pinned commit.
///
/// Here so a test can hold \`unsafe_elements\` against it rather than against
/// anyone's memory of it. They are not required to be equal — tutuca refuses
/// \`base\` as well, see \`unsafe_elements\` — but every entry here must be in
/// tutuca's list, and that is the direction that matters.
pub let spec_baseline_removes : Array[ElementName] = [
${baseline.removeElements.map((e) => `  ${NS[e.namespace]}(${lit(e.name)}),`).join("\n")}
]
`;
}

const out = await generate();
if (process.argv.includes("--check")) {
  const have = readFileSync(OUT, "utf8");
  if (have !== out) {
    console.error(
      `error: ${OUT} differs from freshly generated output.\n` +
        `NOTE: this compares unformatted output against a formatted file, so a\n` +
        `difference here is not proof the spec changed. Run the sanitizer-defaults\n` +
        `task instead — it formats before comparing.`,
    );
    process.exit(1);
  }
  console.log("sanitizer defaults are up to date");
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
