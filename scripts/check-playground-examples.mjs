// Compile-check the playground's editable examples (playground/site/examples/
// *.mbt + their sibling *.tutu). They are standalone teaching editions —
// intentionally NOT the storybook/examples ports — and no moon package
// includes them, so without this check they rot silently when the library API
// moves (it happened: see "drop deprecated Map::new in examples").
//
// An example's views live in its .tutu, exactly as `tutuca gen` expects.
// The browser generates that module on the fly (the View tab), so this check
// runs the SAME generator — viewgen/ compiled to JS — and drops its output
// into the package as extra files, the way compiler.worker.js does. An
// example with no .tutu sibling is checked on its own (a runtime-view
// escape-hatch example is still legal).
//
// Each example is checked one at a time (they all define `fn build()`, so
// they can't share a package) inside a throwaway package whose imports
// mirror the in-browser compiler's environment (see assemble.mjs DIRECT):
// the module-root facade as @tutuca plus the library packages, and the
// moonbitlang/core std packages examples reach for. Run:
//   moon build --target js playground/viewgen_js   # the generator
//   node scripts/check-playground-examples.mjs
import { readdirSync, mkdirSync, rmSync, writeFileSync, copyFileSync, readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { moonPkgImports } from "../playground/build/direct-packages.mjs";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXAMPLES = join(REPO, "playground/site/examples");
const SCAFFOLD = join(REPO, "playground/_examples_check");
const VIEWGEN = join(REPO, "_build/js/debug/build/playground/viewgen_js/viewgen_js.js");

// The aliases the in-browser moonc exposes, DERIVED from the one list rather
// than mirrored: this check only means something if the environment it checks
// in is the environment the page provides, and a hand-copied "mirror" is a
// promise a comment cannot keep. `host` is dropped because examples never
// drive the mount host directly. The std packages below are extra: the browser
// payload bakes all of moonbitlang/core, and these are the ones examples reach
// for.
const MOON_PKG = `// generated by scripts/check-playground-examples.mjs — never committed
import {
${moonPkgImports(["host"]).join("\n")}
  "moonbitlang/core/string",
  "moonbitlang/core/cmp",
  "moonbitlang/core/json",
}

// examples import a subset each; unused-package noise is expected
warnings = "-44"
`;

// The view generator, as the playground page loads it: a classic script
// publishing globalThis.__tutucaViewgen(html, name) -> JSON.
if (!existsSync(VIEWGEN)) {
  console.error(
    `view generator missing: ${VIEWGEN}\n  build it with: moon build --target js playground/viewgen_js`,
  );
  process.exit(1);
}
new Function(readFileSync(VIEWGEN, "utf8"))();

// The component name heads the generated types. A `.tutu` names its
// components itself, in the headings under `spec:` and `view:` — the same
// reading `playground/web/viewgen-client.js` does, spelled here because a
// build script cannot import a browser module.
const HEADING_RE = /^  ([A-Z]\w*)(?:\.\w+)?:/m;
const nameOf = (src) => {
  for (const section of src.split(/^(?=[a-z]+:[ \t]*$)/m)) {
    if (!/^(spec|view):/.test(section)) continue;
    const m = HEADING_RE.exec(section);
    if (m) return m[1];
  }
  return "View";
};

const examples = readdirSync(EXAMPLES).filter((f) => f.endsWith(".mbt")).sort();
const shared = new Set(JSON.parse(readFileSync(join(REPO, "showcase/catalog.json"), "utf8")).map(e => `${e.id}.mbt`));
if (!examples.length) {
  console.error("no examples found in", EXAMPLES);
  process.exit(1);
}

// One unit to check: the MoonBit source, and the view file it reads (null for
// a runtime-view example). The landing page embeds these shared files;
// check-showcase verifies its generated references and copies.
const units = examples.map((name) => ({
  name,
  mbt: readFileSync(join(EXAMPLES, name), "utf8"),
  html: existsSync(join(EXAMPLES, name.replace(/\.mbt$/, ".tutu")))
    ? readFileSync(join(EXAMPLES, name.replace(/\.mbt$/, ".tutu")), "utf8")
    : null,
}));

const failures = [];
try {
  mkdirSync(SCAFFOLD, { recursive: true });
  writeFileSync(join(SCAFFOLD, "moon.pkg"), MOON_PKG);
  for (const { name, mbt, html } of units) {
    writeFileSync(join(SCAFFOLD, "example.mbt"), mbt);

    // The view half, generated as the browser generates it (no
    // moonbitlang/core/debug in the playground package, so no debug derive).
    let views = "";
    let ir = "";
    if (html !== null) {
      const r = JSON.parse(
        globalThis.__tutucaViewgen(html, nameOf(html)),
      );
      if (!r.ok) {
        console.log(`FAILED  ${name}`);
        failures.push([name, `view generation failed: ${r.error}\n`]);
        continue;
      }
      views = r.module;
      ir = r.ir || "";
      // The advisory channel, which this used to drop on the floor. A hint is
      // how `gen` reports the thing that compiles and then does not work — a
      // mutator named as if it were a message, a child view that resolves to
      // nothing — and these are the landing page's own examples, so one firing
      // here is a demo that is wrong in front of a visitor. Fatal for that
      // reason, and for no other: elsewhere a hint is a hint.
      // Shared examples supply tested MoonBit adapters for these declarations.
      // Other diagnostics still fail, and the assembled pair must type-check.
      const hints = (r.hints || []).filter(h => !(shared.has(name) && h.endsWith("(script-refusal)")));
      if (hints.length > 0) {
        console.log(`FAILED  ${name}`);
        failures.push([name, hints.map((h) => `  ${h}`).join("\n") + "\n"]);
        continue;
      }
    }
    writeFileSync(join(SCAFFOLD, "_views.mbt"), views);
    writeFileSync(join(SCAFFOLD, "_views_ir.mbt"), ir);

    try {
      execSync("moon check playground/_examples_check --target js", {
        cwd: REPO,
        stdio: ["ignore", "pipe", "pipe"],
      });
      console.log(`ok      ${name}${views ? "" : "  (no view file)"}`);
    } catch (e) {
      console.log(`FAILED  ${name}`);
      failures.push([name, `${e.stdout ?? ""}${e.stderr ?? ""}`]);
    }
  }
} finally {
  rmSync(SCAFFOLD, { recursive: true, force: true });
}

for (const [name, out] of failures) {
  console.error(`\n=== ${name} ===\n${out}`);
}
console.log(`\n${units.length - failures.length}/${units.length} playground examples compile`);
process.exit(failures.length ? 1 : 0);
